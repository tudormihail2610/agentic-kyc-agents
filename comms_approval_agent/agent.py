import os

from dotenv import load_dotenv
from google import genai
from google.adk.agents import Agent
from google.adk.agents.remote_a2a_agent import RemoteA2aAgent
from google.adk.planners import BuiltInPlanner
from google.genai import types
from google.adk.tools.mcp_tool.mcp_toolset import MCPToolset, StreamableHTTPConnectionParams

load_dotenv()

current_environment = os.getenv("ENV")

project_id = os.getenv("GOOGLE_CLOUD_PROJECT")

client = genai.Client(
    vertexai=True,
    project=project_id,
    location=os.getenv("GOOGLE_CLOUD_LOCATION"),
)

default_planner = BuiltInPlanner(
    thinking_config=types.ThinkingConfig(include_thoughts=True)
)

default_generate_cfg = types.GenerateContentConfig(
    safety_settings=[
        types.SafetySetting(
            category=types.HarmCategory.HARM_CATEGORY_DANGEROUS_CONTENT,
            threshold=types.HarmBlockThreshold.OFF
        )
    ],
)

comms_approval_remote_agent = lambda: RemoteA2aAgent(
    name="comms_approval_agent",
    description="You are an email approval agent. Your only task is to read emails generated by the email generator agent and check for bad messages or misspellings. After reviewing the email content, clearly state—using a single sentence—whether the content of the email is approved.",
    agent_card=("comms-approval-agent.json")
)

root_agent = Agent(
    name="comms_approval_agent",
    model=os.getenv("MODEL"),
    description="You are an email approval agent. Your only task is to read emails generated by the email generator agent and check for bad messages or misspellings. After reviewing the email content, clearly state—using a single sentence—whether the content of the email is approved.",
    instruction="""
    You are an email approval agent. Your only task is to read emails generated by the email generator agent and check for bad messages or misspellings. After reviewing the email content, clearly state—using a single sentence—whether the content of the email is approved.

    # Output Format
    
    - Respond with only a single clear sentence: "Approved." if the content passes, or "Not approved." if any bad message or misspelling is found.
    
    # Notes
    
    - Do not summarize, organize, or take any other action on the email.
    - Do not provide feedback or suggestions—just state approval status in the single sentence.
    - Always check for both inappropriate content and spelling errors before deciding.
    
    REMINDER: Read email content thoroughly, check for bad messages or misspells, and output either "Approved." or "Not approved." as a single sentence.
    """,
    planner=default_planner,
    generate_content_config=default_generate_cfg,
)
